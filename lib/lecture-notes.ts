import type { CourseTopic } from './course-content';
import { deepDives } from './deep-dives';

export type LectureSection = {
  heading: string;
  paragraphs: string[];
  takeaway: string;
};

const methodLens = (topic: CourseTopic, heading: string) =>
  `В теме «${topic.title}» понятие «${heading}» важно рассматривать не изолированно, а как часть исследовательского решения. Сначала формулируют, какое знание требуется получить, затем определяют единицу анализа, источник данных и способ интерпретации. Один и тот же приём может быть уместен для exploratory-вопроса и недостаточен для причинного вывода. Поэтому сильное обоснование всегда связывает вопрос, процедуру, данные и границы вывода.`;

const caseLens = (topic: CourseTopic, heading: string) =>
  `Представим команду, которая исследует новый цифровой сервис. Применяя «${heading}», ей нужно заранее описать участников, контекст использования, конкретную процедуру и признаки, по которым будет сделан вывод. После сбора данных исследователь не просто перечисляет наблюдения, а показывает логическую цепочку: что было замечено, как это было проанализировано и почему это поддерживает вывод именно по теме «${topic.title}».`;

const qualityLens = (topic: CourseTopic, heading: string) =>
  `Качество результата зависит от прозрачности решений. Для «${heading}» полезно зафиксировать критерии включения данных, отклонения от плана, возможные источники bias и альтернативные объяснения. Reliability относится к устойчивости процедуры или измерения, validity — к обоснованности интерпретации, а generalisability или transferability — к условиям переноса результата. Эти свойства нельзя заменить одним большим числом участников.`;

const ethicsLens = (topic: CourseTopic) =>
  `Даже если основной вопрос посвящён теме «${topic.title}», исследователь обязан оценить нагрузку на участников, добровольность согласия, приватность и минимизацию данных. Нужно собирать только необходимое, объяснять право выйти без негативных последствий и заранее определить срок хранения. Этическое решение является частью методологии: давление, неясная инструкция или небезопасная среда способны одновременно причинить вред и исказить данные.`;

const examLens = (topic: CourseTopic, heading: string) =>
  `В экзаменационном ответе о «${heading}» сначала дай точное определение, затем объясни механизм и тип получаемых данных. После этого назови преимущество, существенное ограничение и способ уменьшить риск. Заверши применением к конкретному кейсу. Формула «выбираю метод, потому что он быстрый» слаба; формула «выбираю его, потому что исследовательский вопрос требует такого типа evidence, при этом учитываю такое-то ограничение» показывает методологическое мышление.`;

export function buildLectureSections(topic: CourseTopic): LectureSection[] {
  const source = [
    ...topic.sections.map((section) => ({ ...section, tip: '' })),
    ...(deepDives[topic.id] ?? []),
  ];

  return source.map((section, index) => ({
    heading: section.heading,
    paragraphs: [
      section.body,
      methodLens(topic, section.heading),
      caseLens(topic, section.heading),
      qualityLens(topic, section.heading),
      index % 2 === 0 ? ethicsLens(topic) : examLens(topic, section.heading),
      index % 2 === 0 ? examLens(topic, section.heading) : ethicsLens(topic),
    ],
    takeaway:
      section.tip ||
      `Связывай «${section.heading}» с исследовательским вопросом, данными и ограничениями вывода.`,
  }));
}
